const assert=require("node:assert/strict");
const E=require("../engine.js");
const state=E.initial();
assert.equal(state.zones.length,6);
assert.equal(state.varieties.length,8);
const tomato={...state.varieties.find(v=>v.id==="cv-germanpink"),maturityDays:90,maturityBasis:"transplant"};
const sunny={...state.zones.find(z=>z.id==="zone-sunny"),sunHours:8};
const shade={...state.zones.find(z=>z.id==="zone-steps"),sunHours:2};
state.profile.firstFrost="09-10";
let assessment=E.assessment(tomato,sunny,state,"2027-07-15");
assert.match(assessment.rating,/High risk/);
assert.ok(assessment.checks.some(c=>c.name==="Harvest window"&&c.level==="risk"));
assessment=E.assessment(tomato,shade,state,"2027-06-01");
assert.ok(assessment.checks.some(c=>c.name==="Direct sunlight"&&c.level==="risk"));
assert.ok(assessment.missing.length>0);
assert.equal(E.assessment(state.varieties[0],sunny,state,"2027-06-01").missing.some(s=>s.includes("cultivar-specific")),true);
assert.deepEqual(E.parseCatalog("Determinate tomato. Full sun, 60 to 70 days, soil temperature 60 F"),{maturityDays:70,habit:"determinate",sunMin:6,soilMin:60});
const csv=E.parseWeatherCSV("timestamp,metric,value,source\n2026-10-08T07:30:00-06:00,night_low_f,38.2,manual");
assert.equal(csv.imported.length,1);
assert.equal(csv.imported[0].metric,"night_low_f");
assert.equal(E.parseWeatherCSV("dateutc,tempf\n2026-10-08T08:00:00-06:00,34.5").imported[0].metric,"air_temp_f");
assert.equal(E.getEffective({flag:"suspect",value:14.8}),null);
assert.equal(E.getEffective({flag:"verified",value:14.8,verifiedValue:6.5}),6.5);
assert.ok(E.getEffective({flag:"ok",value:6.2})===6.2);
state.forecast={daily:{time:["2027-06-01"],temperature_2m_min:[28]}};
assert.ok(E.assessment(tomato,sunny,state,"2027-06-01").checks.some(c=>c.name==="Modeled transplant-date frost"));
console.log("PASS: zones, variety data, seasonal and sun screening, catalog import, weather CSV, raw/verified snow, forecast frost");
